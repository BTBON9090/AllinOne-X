import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../shared/fill-generators.js', import.meta.url), 'utf8'), context);
const numbers = (count, settings) => Array.from(context.generateSmartNumberSeries(count, settings));
const times = (count, settings) => Array.from(context.generateSmartTimeSeries(count, settings));
assert.deepEqual(numbers(4, { start:2, step:0 }), ['2','2','2','2']);
assert.deepEqual(numbers(4, { sequenceType:'geometric', start:2, ratio:0 }), ['2','0','0','0']);
assert.deepEqual(numbers(4, { start:1, step:-0.25, decimals:2 }), ['1.00','0.75','0.50','0.25']);
assert.deepEqual(numbers(6, { sequenceType:'fibonacci', start:0, second:1 }), ['0','1','1','2','3','5']);
assert.deepEqual(numbers(5, { sequenceType:'prime', start:10 }), ['11','13','17','19','23']);
assert.deepEqual(numbers(4, { sequenceType:'factorial', start:0 }), ['1','1','2','6']);
assert.deepEqual(numbers(3, { sequenceType:'odd', start:-4 }), ['-3','-1','1']);
assert.deepEqual(numbers(3, { sequenceType:'even', start:-3 }), ['-2','0','2']);
assert.deepEqual(numbers(3, { sequenceType:'square', start:2 }), ['4','9','16']);
assert.deepEqual(numbers(3, { sequenceType:'triangular', start:1 }), ['1','3','6']);
assert.deepEqual(numbers(3, { sequenceType:'natural', start:2 }), ['2','3','4']);
assert.deepEqual(numbers(2, { start:1000, step:0.5, decimals:2, thousands:true }), ['1,000.00','1,000.50']);
assert.throws(() => numbers(3, { sequenceType:'factorial', start:18 }), /0–18/);
assert.throws(() => numbers(3, { sequenceType:'prime', start:10000001 }), /10,000,000/);
assert.throws(() => numbers(10001, {}), /10,000/);
assert.throws(() => numbers(4, { sequenceType:'geometric', start:1, ratio:1e10 }), /安全数值/);
assert.throws(() => numbers(1, { start:Infinity }), /有效/);
assert.throws(() => numbers(1, { decimals:NaN }), /有效/);
assert.deepEqual(times(3, { start:'23:59:30', stepSeconds:30 }), ['23:59:30','00:00:00','00:00:30']);
assert.deepEqual(times(3, { start:'00:00', stepSeconds:-30 }), ['00:00:00','23:59:30','23:59:00']);
assert.deepEqual(times(2, { start:'08:05', stepSeconds:0, format:'H:m:s' }), ['8:5:0','8:5:0']);
assert.throws(() => times(2, { start:'25:00' }), /23:59:59/);
assert.throws(() => times(2, { start:'12:80' }), /23:59:59/);
assert.throws(() => times(2, { stepSeconds:1.5 }), /整数秒/);
console.log('Sequence checks passed: all 10 number series, zero/negative parameters, precision/overflow limits, and midnight time wrapping.');
